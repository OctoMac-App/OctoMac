#!/usr/bin/env bash
# Builds llms-full.txt: the project's documents in one file, for AI tools that want everything in a single download.
# llms.txt (written by hand) links to them instead. Run this after changing any of the documents below.
#
#   scripts/make-llms-full.sh          # rewrite llms-full.txt
#   scripts/make-llms-full.sh --check  # fail if llms-full.txt is out of date (used by CI)
set -euo pipefail
cd "$(dirname "$0")/.."

DOCS=(README.md PRIVACY.md CONTRIBUTING.md CLAUDE.md)
BLOB="https://github.com/OctoMac-App/OctoMac/blob/master"
RAW="https://raw.githubusercontent.com/OctoMac-App/OctoMac/master"

build() {
  # The summary from llms.txt: its title and quoted description.
  sed -n '1,/^> /p' llms.txt
  echo
  echo "This file is generated by scripts/make-llms-full.sh from: ${DOCS[*]}."
  for doc in "${DOCS[@]}"; do
    echo
    echo "---"
    echo
    echo "<!-- $doc -->"
    echo
    # Relative links and images point at the repository, since this file is read on its own.
    sed -E \
      -e "s#\]\((docs/[^)]+)\)#](${RAW}/\1)#g" \
      -e "s#(src|srcset)=\"(docs/[^\"]+)\"#\1=\"${RAW}/\2\"#g" \
      -e "s#\]\(([A-Za-z]+\.md|LICENSE)\)#](${BLOB}/\1)#g" \
      "$doc"
  done
}

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -q <(build) llms-full.txt >/dev/null; then
    echo "llms-full.txt is out of date. Run scripts/make-llms-full.sh and commit the result." >&2
    exit 1
  fi
  echo "llms-full.txt is up to date."
else
  build > llms-full.txt
  echo "Wrote llms-full.txt ($(wc -c < llms-full.txt | tr -d ' ') bytes)"
fi
